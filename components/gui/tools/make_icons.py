#!/usr/bin/env python3
"""Generate the bridge icons as LVGL ARGB8888 image sources.

The generic icons (keyboard, mouse, computer) are drawn here (white on
transparent, like the other status icons); the ZMK logo is rasterized from
ZMK's own SVG (MIT, The ZMK Contributors). Usage:

    python3 make_icons.py <out_dir> [--zmk-svg path/to/zmk_logo.svg] [--preview out.png]

Needs Pillow; the ZMK logo also needs rsvg-convert (librsvg).
"""
import argparse
import os
import subprocess
import tempfile

from PIL import Image, ImageDraw

SIZE = 32
SS = 8  # supersampling factor for smooth edges


def canvas():
    return Image.new("RGBA", (SIZE * SS, SIZE * SS), (0, 0, 0, 0))


def finish(img):
    return img.resize((SIZE, SIZE), Image.LANCZOS)


def s(v):
    return int(round(v * SS))


def keyboard():
    img = canvas()
    d = ImageDraw.Draw(img)
    w = 2.2
    d.rounded_rectangle([s(1.5), s(8), s(30.5), s(25)], radius=s(3), outline="white", width=s(w))
    # three rows of keys, the last one with a space bar
    for row, y in enumerate((11.6, 15.4)):
        for i in range(6):
            x = 5.2 + i * 4.3
            d.rounded_rectangle([s(x), s(y), s(x + 2.6), s(y + 2.3)], radius=s(0.6), fill="white")
    d.rounded_rectangle([s(5.2), s(19.4), s(8.0), s(21.7)], radius=s(0.6), fill="white")
    d.rounded_rectangle([s(9.8), s(19.4), s(22.2), s(21.7)], radius=s(0.6), fill="white")
    d.rounded_rectangle([s(24.0), s(19.4), s(26.8), s(21.7)], radius=s(0.6), fill="white")
    return finish(img)


def mouse():
    img = canvas()
    d = ImageDraw.Draw(img)
    w = 2.2
    d.rounded_rectangle([s(8.5), s(3), s(23.5), s(29)], radius=s(7.5), outline="white", width=s(w))
    d.line([s(8.5), s(13), s(23.5), s(13)], fill="white", width=s(w))
    d.line([s(16), s(3), s(16), s(13)], fill="white", width=s(w))
    d.rounded_rectangle([s(14.8), s(6.5), s(17.2), s(10.5)], radius=s(1.2), fill="white")
    return finish(img)


def computer():
    img = canvas()
    d = ImageDraw.Draw(img)
    w = 2.2
    d.rounded_rectangle([s(2), s(4), s(30), s(22)], radius=s(2), outline="white", width=s(w))
    d.polygon([(s(13), s(22)), (s(19), s(22)), (s(20.5), s(26.5)), (s(11.5), s(26.5))], fill="white")
    d.rounded_rectangle([s(8), s(26), s(24), s(28.6)], radius=s(1.2), fill="white")
    return finish(img)


def zmk_logo(svg):
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, "zmk.png")
        subprocess.run(["rsvg-convert", "-w", str(SIZE * SS), "-h", str(SIZE * SS), svg, "-o", png],
                       check=True)
        img = Image.open(png).convert("RGBA")
    return finish(img)


def write_c(img, name, out_dir, source_note):
    # LVGL ARGB8888 is stored little-endian: B, G, R, A per pixel
    rgba = img.tobytes()
    data = bytearray(len(rgba))
    data[0::4], data[1::4], data[2::4], data[3::4] = rgba[2::4], rgba[1::4], rgba[0::4], rgba[3::4]
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ",")
    body = "\n".join(lines)
    c = f"""// Generated by components/gui/tools/make_icons.py -- do not edit.
// {source_note}

#include "lvgl.h"

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_data[] = {{
{body}
}};

const lv_image_dsc_t {name} = {{
    .header =
        {{
            .magic = LV_IMAGE_HEADER_MAGIC,
            .cf = LV_COLOR_FORMAT_ARGB8888,
            .w = {img.width},
            .h = {img.height},
            .stride = {img.width * 4},
        }},
    .data_size = sizeof({name}_data),
    .data = {name}_data,
}};
"""
    with open(os.path.join(out_dir, f"{name}.c"), "w") as f:
        f.write(c)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("out_dir")
    p.add_argument("--zmk-svg")
    p.add_argument("--preview")
    a = p.parse_args()
    os.makedirs(a.out_dir, exist_ok=True)
    icons = [
        (keyboard(), "icon_keyboard", "Generic keyboard icon, drawn by make_icons.py."),
        (mouse(), "icon_mouse", "Generic mouse icon, drawn by make_icons.py."),
        (computer(), "icon_computer", "Generic computer icon, drawn by make_icons.py."),
    ]
    if a.zmk_svg:
        icons.append((zmk_logo(a.zmk_svg), "icon_zmk_logo",
                      "ZMK logo, from zmk/docs/static/img/zmk_logo.svg "
                      "(MIT License, Copyright (c) 2020 The ZMK Contributors)."))
    for img, name, note in icons:
        write_c(img, name, a.out_dir, note)
    if a.preview:
        # the dongle's screen is 160x80 on black; show every icon at 4x
        scale = 4
        sheet = Image.new("RGBA", ((SIZE + 8) * len(icons) * scale, (SIZE + 8) * scale), "black")
        for i, (img, _, _) in enumerate(icons):
            big = img.resize((SIZE * scale, SIZE * scale), Image.NEAREST)
            sheet.alpha_composite(big, (((SIZE + 8) * i + 4) * scale, 4 * scale))
        sheet.save(a.preview)


if __name__ == "__main__":
    main()
